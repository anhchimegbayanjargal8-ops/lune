import { getStorageImageUrl, productImagePath } from "./supabase/storage";

export type ProductImageType = "front" | "back" | "side" | "fabric" | "model";

export interface ProductImage {
  type: ProductImageType;
  url: string;
  alt: string;
}

export const PRODUCT_IMAGE_TYPE_LABEL: Record<ProductImageType, string> = {
  front: "Front",
  back: "Back",
  side: "Side / Detail",
  fabric: "Fabric Close-up",
  model: "On Model",
};

export const PRODUCT_IMAGE_TYPE_ORDER: ProductImageType[] = ["front", "back", "side", "fabric", "model"];

/**
 * ============================================================================
 *  HOW TO REPLACE PLACEHOLDER PHOTOGRAPHY WITH YOUR OWN IMAGES
 * ============================================================================
 * Every product's gallery is generated by `getProductImages()` below, and
 * every page/component reads through it — so you never need to touch
 * ProductCard, ProductGallery, the product page, or mock-data.ts to swap
 * photography. Pick ONE of these:
 *
 * OPTION A — Admin → Manage Products → Manage Images (recommended)
 *   Sign in to /admin, open a product, and upload each shot there. This
 *   uploads straight to the public "product-images" Storage bucket using
 *   the exact convention below, AND records that the upload exists so the
 *   storefront knows to use it instead of the placeholder (see
 *   src/lib/admin/image-manifest.ts + src/hooks/useProductImages.ts).
 *   Uploaded images appear on the product page automatically — no code or
 *   redeploy needed.
 *
 *     product-images/<product-slug>/front.jpg
 *     product-images/<product-slug>/back.jpg
 *     product-images/<product-slug>/side.jpg
 *     product-images/<product-slug>/fabric.jpg
 *     product-images/<product-slug>/model.jpg
 *
 * OPTION B — Hardcode a URL
 *   Paste any hosted image URL directly into PRODUCT_IMAGE_OVERRIDES below,
 *   keyed by the product's slug. You can override just one image type
 *   (e.g. only `front`) and leave the rest on the admin uploader or
 *   placeholders — they combine per image type.
 *
 * Until either is set up, every product falls back to a stable placeholder
 * photo so the site never shows a broken image.
 *
 * Note: this function stays synchronous and server-safe on purpose (it
 * runs at module-load inside src/lib/mock-data.ts), so it intentionally
 * does NOT guess that a Storage file exists just because Supabase is
 * configured — that used to risk a broken image for any shot that hadn't
 * actually been uploaded yet. Live admin uploads are instead layered on
 * top, client-side, by the `useProductImages` hook, which knows for
 * certain an upload succeeded before it swaps the image in.
 * ============================================================================
 */
export const PRODUCT_IMAGE_OVERRIDES: Partial<Record<string, Partial<Record<ProductImageType, string>>>> = {
  // Example:
  // "silk-slip-dress-ivory": {
  //   front: "https://your-cdn.com/silk-slip-dress/front.jpg",
  //   model: "https://your-cdn.com/silk-slip-dress/model.jpg",
  // },
};

function placeholderUrl(seed: string, w = 1000, h = 1300): string {
  return `https://picsum.photos/seed/${seed}/${w}/${h}`;
}

/**
 * Returns the full 5-shot gallery (front, back, side/detail, fabric
 * close-up, model) for a single product. `seedPrefix` only affects the
 * placeholder fallback — it has no effect once an override URL or an
 * admin-uploaded image exists for that image type.
 */
export function getProductImages(slug: string, seedPrefix: string, productName: string): ProductImage[] {
  return PRODUCT_IMAGE_TYPE_ORDER.map((type) => {
    const override = PRODUCT_IMAGE_OVERRIDES[slug]?.[type];
    const url = override ?? placeholderUrl(`${seedPrefix}-${type}`);
    return { type, url, alt: `${productName} — ${PRODUCT_IMAGE_TYPE_LABEL[type]}` };
  });
}

// Re-exported so admin/storage code can build the exact same Storage path
// convention without duplicating it.
export { getStorageImageUrl, productImagePath };
